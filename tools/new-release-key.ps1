<#
.SYNOPSIS
    Creates the release signing key (once) and embeds its public half in the app.
.DESCRIPTION
    Every release's latest.json is signed with this key, and the app only installs updates whose signature
    matches the public key compiled into it. The private key stays OUTSIDE the repository:

        %USERPROFILE%\.standmate\release-key.xml

    BACK IT UP (e.g. a password manager or an offline drive). If it's lost, existing installs can't verify new
    releases any more: everyone would need to reinstall manually once from a build with a new key.
.EXAMPLE
    powershell -ExecutionPolicy Bypass -File tools\new-release-key.ps1
#>
param([string]$KeyPath = (Join-Path $env:USERPROFILE '.standmate\release-key.xml'), [switch]$Force)

$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot -Parent
$csPath = Join-Path $root 'src\StandMate\Platform\ReleaseKey.cs'

if ((Test-Path $KeyPath) -and -not $Force) {
    Write-Host "Using the existing key at $KeyPath"
    $rsa = New-Object System.Security.Cryptography.RSACryptoServiceProvider
    $rsa.PersistKeyInCsp = $false
    $rsa.FromXmlString((Get-Content -Raw $KeyPath))
} else {
    $rsa = New-Object System.Security.Cryptography.RSACryptoServiceProvider 3072
    $rsa.PersistKeyInCsp = $false
    New-Item -ItemType Directory -Force (Split-Path $KeyPath) | Out-Null
    [IO.File]::WriteAllText($KeyPath, $rsa.ToXmlString($true))
    # Readable by the current user only.
    icacls $KeyPath /inheritance:r /grant:r "$($env:USERNAME):F" | Out-Null
    Write-Host "New private key: $KeyPath  <-- back this up, never commit it"
}

$public = $rsa.ToXmlString($false)
$cs = @"
namespace StandMate.Platform
{
    /// <summary>
    /// Public half of the release signing key (generated by tools/new-release-key.ps1). Updates are only installed
    /// when latest.json is signed by the matching private key, which never leaves the developer's machine.
    /// </summary>
    internal static class ReleaseKey
    {
        public const string PublicKeyXml =
            "$public";
    }
}
"@
[IO.File]::WriteAllText($csPath, $cs, (New-Object System.Text.UTF8Encoding $false))
Write-Host "Public key written to $csPath"
